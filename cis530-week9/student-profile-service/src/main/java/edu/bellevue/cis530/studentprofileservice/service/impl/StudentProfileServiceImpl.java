package edu.bellevue.cis530.studentprofileservice.service.impl;

import java.util.List;

import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;

import lombok.RequiredArgsConstructor;

import edu.bellevue.cis530.studentprofileservice.entity.StudentProfile;
import edu.bellevue.cis530.studentprofileservice.repository.StudentProfileRepository;
import edu.bellevue.cis530.studentprofileservice.service.StudentProfileService;

/*
 * Implements the business logic for StudentProfile operations.
 * This class uses StudentProfileRepository to communicate
 * with the student_profile_db database.
 */
@Service
@RequiredArgsConstructor
public class StudentProfileServiceImpl implements StudentProfileService {

    // Constructor injection is generated by Lombok.
    private final StudentProfileRepository studentProfileRepository;

    @Override
    public StudentProfile createProfile(StudentProfile profile) {

        // Save the new profile and return the saved record.
        return studentProfileRepository.save(profile);
    }

    @Override
    public List<StudentProfile> getAllProfiles() {

        // Retrieve and return all student profiles.
        return studentProfileRepository.findAll();
    }

    @Override
    public StudentProfile getProfileById(Long id) {

        // Find the profile by ID or return an HTTP 404 error
        // when the requested profile does not exist.
        return studentProfileRepository.findById(id)
                .orElseThrow(() -> new ResponseStatusException(
                        HttpStatus.NOT_FOUND,
                        "Student profile not found with ID: " + id));
    }

    @Override
    public StudentProfile getProfileByStudentId(Long studentId) {

        // Find the profile associated with the specified student.
        // Return HTTP 404 if no matching profile exists.
        return studentProfileRepository.findByStudentId(studentId)
                .orElseThrow(() -> new ResponseStatusException(
                        HttpStatus.NOT_FOUND,
                        "Student profile not found for student ID: " + studentId));
    }

    @Override
    public void deleteProfile(Long id) {

        // Verify that the profile exists before attempting deletion.
        if (!studentProfileRepository.existsById(id)) {
            throw new ResponseStatusException(
                    HttpStatus.NOT_FOUND,
                    "Student profile not found with ID: " + id);
        }

        // Delete the profile record from the database.
        studentProfileRepository.deleteById(id);
    }
}