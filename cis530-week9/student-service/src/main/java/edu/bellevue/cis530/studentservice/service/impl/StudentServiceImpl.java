package edu.bellevue.cis530.studentservice.service.impl;

import java.util.List;

import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;

import lombok.RequiredArgsConstructor;

import edu.bellevue.cis530.studentservice.entity.Student;
import edu.bellevue.cis530.studentservice.repository.StudentRepository;
import edu.bellevue.cis530.studentservice.service.StudentService;

/*
 * Implements the business logic for Student operations.
 * This class uses StudentRepository to communicate with
 * the student_db database.
 */
@Service
@RequiredArgsConstructor
public class StudentServiceImpl implements StudentService {

    // Constructor injection is generated by Lombok.
    private final StudentRepository studentRepository;

    @Override
    public Student createStudent(Student student) {

        // Save the new student and return the saved record.
        return studentRepository.save(student);
    }

    @Override
    public List<Student> getAllStudents() {

        // Retrieve and return all students from the database.
        return studentRepository.findAll();
    }

    @Override
    public Student getStudentById(Long id) {

        // Find the student by ID or return an HTTP 404 error
        // when the requested student does not exist.
        return studentRepository.findById(id)
                .orElseThrow(() -> new ResponseStatusException(
                        HttpStatus.NOT_FOUND,
                        "Student not found with ID: " + id));
    }

    @Override
    public void deleteStudent(Long id) {

        // Verify that the student exists before attempting deletion.
        if (!studentRepository.existsById(id)) {
            throw new ResponseStatusException(
                    HttpStatus.NOT_FOUND,
                    "Student not found with ID: " + id);
        }

        // Delete the student record from the database.
        studentRepository.deleteById(id);
    }
}